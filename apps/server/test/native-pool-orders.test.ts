import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { captureBaseline, decide, hash, reduceDecision, stableId } from '../src/tournament/domain';
import { poolOrderStatus, poolResultBasis } from '../src/tournament/poolOrders';
import {
  Decision,
  Baseline,
  LiveState,
  type TournamentState,
  type TournamentCommand,
} from '../src/tournament/schemas';
import { envelope, pureBaseline } from './helpers/nativeLiveFixture';

function initial(optIn = true) {
  const baseline = pureBaseline();
  if (optIn) baseline.settings.poolOrderPolicy = 'unique_set_wins_v1';
  return captureBaseline(baseline);
}
function apply(state: TournamentState, command: TournamentCommand, operator = true) {
  const decision = Decision.parse(
    decide(state, envelope(command, { operator, actorId: crypto.randomUUID() }))!,
  );
  return LiveState.parse(reduceDecision(state, decision));
}
const score = (m: TournamentState['matches'][number], reverse = false) => ({
  kind: 'score' as const,
  matchId: m.id,
  expectedRevision: m.revision,
  score1: reverse ? 0 : 2,
  score2: reverse ? 2 : 0,
  outcome: 'played' as const,
});
function complete(state: TournamentState, poolId?: string) {
  for (const m of state.matches.filter((m) => !poolId || m.poolId === poolId))
    state = apply(state, score(m));
  return state;
}
function rule(state: TournamentState, order = state.pools[0]!.entrantIds) {
  const p = state.pools[0]!;
  return apply(state, {
    kind: 'placements',
    poolId: p.id,
    expectedRevision: p.revision,
    order,
    matchRevisions: Object.fromEntries(
      state.matches.filter((m) => m.poolId === p.id).map((m) => [m.id, m.revision]),
    ),
  });
}
function tied() {
  let state = initial();
  const pool = state.pools[0]!;
  state = complete(state, pool.id);
  // A > B > C > A, each wins against D: three equal set-win totals.
  return apply(
    state,
    score(
      state.matches.find(
        (m) => m.player1Id === pool.entrantIds[0] && m.player2Id === pool.entrantIds[2],
      )!,
      true,
    ),
  );
}

describe('opted-in automatic pool orders', () => {
  it('replays an immutable pre-policy V1 journal with its exact original state hash and manual semantics', () => {
    // Generated by the domain at e691620, before automatic placement policy existed.
    // The third fact repeats an official score and historically clears a manual order.
    const journal = JSON.parse(
      readFileSync(new URL('./fixtures/native-pool-order-v1.json', import.meta.url), 'utf8'),
    );
    expect(journal.sourceCommit).toBe('e691620');
    const baseline = Baseline.parse(journal.baseline);
    const decisions = (journal.decisions as unknown[]).map((d) => Decision.parse(d));
    const state = decisions.reduce(reduceDecision, captureBaseline(baseline));
    expect(hash(state)).toBe(journal.stateHash);
    expect(state.settings.poolOrderPolicy).toBeUndefined();
    expect(state.pools[0]!.order).toBeNull();
    expect(state.pools[0]!.orderDecision).toBeUndefined();
    expect(decide(state, envelope(score(state.matches[0]!)))!.version).toBe(1);
  });

  it('decides and versions a unique set-win order in the last official score fact, touching only its pool', () => {
    const before = initial();
    const pool = before.pools[0]!;
    let state = before;
    const matches = state.matches.filter((m) => m.poolId === pool.id);
    for (const m of matches.slice(0, -1)) state = apply(state, score(m));
    expect(state.pools[0]!.order).toBeNull();
    const request = envelope(score(matches.at(-1)!));
    const decision = Decision.parse(decide(state, request)!);
    expect(decision.version).toBe(2);
    const after = reduceDecision(state, decision);
    expect(after.pools[0]!.order).toEqual(pool.entrantIds);
    expect(after.pools[0]!.orderDecision).toMatchObject({
      source: 'automatic',
      commandId: request.id,
      resultBasis: poolResultBasis(after, after.pools[0]!),
    });
    expect(after.pools[0]!.orderDecision!.matchRevisions[matches.at(-1)!.id]).toBe(1);
    expect(after.pools[1]).toEqual(before.pools[1]);
    expect(poolOrderStatus(after, after.pools[0]!).status).toBe('automatic');
    expect(decide(after, request)).toBeUndefined();
    expect(() => decide(after, { ...request, command: score(after.matches[0]!) })).toThrow(
      /identifier/,
    );
  });

  it('counts explicit forfeits as one set win with no invented games', () => {
    let state = initial();
    const pool = state.pools[0]!;
    for (const m of state.matches.filter((m) => m.poolId === pool.id))
      state = apply(state, {
        ...score(m),
        outcome: 'forfeit',
        score1: null,
        score2: null,
        winnerId: m.player1Id!,
      });
    expect(state.pools[0]!.order).toEqual(pool.entrantIds);
    expect(
      state.matches
        .filter((m) => m.poolId === pool.id)
        .every((m) => m.score1 === null && m.score2 === null),
    ).toBe(true);
  });

  it('leaves ties for an explicit ruling even when games or a head-to-head result could choose an order', () => {
    let state = tied();
    expect(state.pools[0]!.order).toBeNull();
    expect(poolOrderStatus(state, state.pools[0]!).status).toBe('ruling_required');
    state = rule(state, [...state.pools[0]!.entrantIds].reverse());
    expect(state.pools[0]!.orderDecision!.source).toBe('manual');
  });

  it('preserves a manual tie ruling through identical confirmations and availability changes, invalidating it on actual correction', () => {
    let state = rule(tied());
    const ruling = state.pools[0]!.orderDecision;
    const m = state.matches[0]!;
    state = apply(state, { ...score(m), score1: m.score1, score2: m.score2 });
    expect(state.pools[0]!.orderDecision).toEqual(ruling);
    const entrant = state.entrants[0]!;
    state = apply(state, {
      kind: 'availability',
      reason: 'Tournament ruling',
      playerId: entrant.playerId,
      expectedRevision: entrant.revision,
      availability: 'withdrawn',
    });
    expect(state.pools[0]!.orderDecision).toEqual(ruling);
    expect(state.pools[0]!.order).toEqual(ruling!.order);
    state = apply(state, {
      kind: 'availability',
      reason: 'Tournament ruling',
      playerId: entrant.playerId,
      expectedRevision: entrant.revision + 1,
      availability: 'available',
    });
    expect(state.pools[0]!.orderDecision).toEqual(ruling);
    // A games-only correction is still new official evidence, requiring a new ruling.
    state = apply(state, { ...score(state.matches[0]!), score2: 1 });
    expect(state.pools[0]!.order).toBeNull();
    expect(state.pools[0]!.orderDecision).toBeUndefined();
  });

  it('suspends a manual order only for current pending reports and restores it when rejected', () => {
    let state = rule(tied());
    const ruling = state.pools[0]!.orderDecision;
    state = apply(state, score(state.matches[0]!, true), false);
    expect(state.pools[0]!.order).toBeNull();
    expect(poolOrderStatus(state, state.pools[0]!).status).toBe('review_pending');
    expect(() => rule(state)).toThrow(/current score reports/);
    const report = state.reports.at(-1)!;
    state = apply(state, {
      kind: 'review',
      reportId: report.id,
      expectedRevision: state.matches[0]!.revision,
      approve: false,
    });
    expect(state.pools[0]!.order).toEqual(ruling!.order);
    expect(state.pools[0]!.orderDecision).toEqual(ruling);
    state = apply(state, score(state.matches[0]!, true), false);
    // Operator correction supersedes the pending report's old revision.
    state = apply(state, { ...score(state.matches[0]!), score2: 1 });
    expect(state.reports.at(-2)!.status).toBe('pending');
    expect(poolOrderStatus(state, state.pools[0]!).status).toBe('ruling_required');
  });

  it('waits for TO approval, then recomputes only the official reviewed result', () => {
    let state = initial();
    state.settings.scoreReportingMode = 'to_review';
    const pool = state.pools[0]!;
    const matches = state.matches.filter((m) => m.poolId === pool.id);
    for (const m of matches.slice(0, -1)) state = apply(state, score(m));
    state = apply(state, score(matches.at(-1)!), false);
    expect(state.pools[0]!.order).toBeNull();
    state = apply(state, {
      kind: 'review',
      reportId: state.reports.at(-1)!.id,
      expectedRevision: 0,
      approve: true,
    });
    expect(state.pools[0]!.order).toEqual(pool.entrantIds);
  });

  it('replaces a suspended automatic order only when a conflicting report becomes official', () => {
    let state = initial();
    state = complete(state, state.pools[0]!.id);
    const original = state.pools[0]!.orderDecision!;
    state = apply(state, score(state.matches[0]!, true), false);
    expect(state.pools[0]!.order).toBeNull();
    expect(state.pools[0]!.orderDecision).toEqual(original);
    state = apply(state, {
      kind: 'review',
      reportId: state.reports.at(-1)!.id,
      expectedRevision: state.matches[0]!.revision,
      approve: true,
    });
    expect(state.pools[0]!.order).toEqual([
      original.order[1],
      original.order[0],
      ...original.order.slice(2),
    ]);
    expect(state.pools[0]!.orderDecision!.source).toBe('automatic');
    expect(state.pools[0]!.orderDecision!.resultBasis).not.toBe(original.resultBasis);
  });

  it('counts every official meeting in a double round robin without inventing a head-to-head tiebreak', () => {
    const baseline = pureBaseline();
    baseline.settings.poolOrderPolicy = 'unique_set_wins_v1';
    baseline.structureOptions = { roundRobinMeetings: 2 };
    const firstMeetingIds = new Set(baseline.matches.map((m) => m.id));
    baseline.matches.push(
      ...baseline.matches.map((m) => ({
        ...m,
        id: stableId(`second:${m.id}`),
        sourceKey: `second:${m.id}`,
      })),
    );
    let state = captureBaseline(baseline);
    for (const m of state.matches) state = apply(state, score(m, !firstMeetingIds.has(m.id)));
    expect(state.pools.every((p) => p.order === null)).toBe(true);
    expect(state.pools.map((p) => poolOrderStatus(state, p).status)).toEqual([
      'ruling_required',
      'ruling_required',
    ]);
  });

  it('requires a full-order ruling even when the only tied entrants are withdrawn', () => {
    let state = initial();
    const pool = state.pools[0]!;
    state = complete(state, pool.id);
    const reverse = state.matches.find(
      (m) => m.player1Id === pool.entrantIds[1] && m.player2Id === pool.entrantIds[3],
    )!;
    state = apply(state, score(reverse, true));
    for (const playerId of pool.entrantIds.slice(1))
      state = apply(state, {
        kind: 'availability',
        playerId,
        expectedRevision: 0,
        availability: 'withdrawn',
        reason: 'Left after completing pools',
      });
    expect(state.pools[0]!.order).toBeNull();
    expect(poolOrderStatus(state, state.pools[0]!).status).toBe('ruling_required');
    state = rule(state);
    expect(state.pools[0]!.order).toEqual(pool.entrantIds);
  });

  it('requires withdrawal forfeits, retains played results, and preserves existing active-entrant qualification', () => {
    let state = initial();
    const pool = state.pools[0]!;
    const withdrawn = pool.entrantIds[3]!;
    const played = state.matches.find(
      (m) => m.player1Id === pool.entrantIds[0] && m.player2Id === withdrawn,
    )!;
    state = apply(state, score(played));
    const evidence = structuredClone(state.matches.find((m) => m.id === played.id)!);
    const entrant = state.entrants.find((e) => e.playerId === withdrawn)!;
    state = apply(state, {
      kind: 'availability',
      reason: 'Tournament ruling',
      playerId: withdrawn,
      expectedRevision: entrant.revision,
      availability: 'withdrawn',
    });
    expect(state.pools[0]!.order).toBeNull();
    for (const m of state.matches.filter((m) => m.status !== 'complete'))
      state = apply(
        state,
        [m.player1Id, m.player2Id].includes(withdrawn)
          ? { ...score(m), outcome: 'forfeit', score1: null, score2: null, winnerId: m.player1Id! }
          : score(m),
      );
    expect(state.matches.find((m) => m.id === played.id)).toEqual(evidence);
    expect(state.pools[0]!.order).toEqual(pool.entrantIds);
    state = apply(state, { kind: 'drawFinals' });
    expect(state.brackets.every((b) => !b.entrantIds.includes(withdrawn))).toBe(true);
    expect(
      state.brackets.find((b) => b.division === 'upper' && b.stage === 'main')!.entrantIds,
    ).toHaveLength(2);
  });

  it('preserves frozen finals and rejects actual pool corrections even after automatic placement', () => {
    let state = apply(complete(initial()), { kind: 'drawFinals' });
    const brackets = structuredClone(state.brackets);
    const finals = structuredClone(state.matches.filter((m) => m.bracketId));
    expect(() => apply(state, score(state.matches[0]!, true))).toThrow(
      /Finals use this pool result/,
    );
    state = apply(state, {
      ...score(state.matches[0]!),
      score1: state.matches[0]!.score1,
      score2: state.matches[0]!.score2,
    });
    expect(state.brackets).toEqual(brackets);
    expect(state.matches.filter((m) => m.bracketId)).toEqual(finals);
  });

  it('keeps old baseline/V1 decisions manual on new writes and folds historical decisions without policy reevaluation', () => {
    const before = initial(false);
    let state = before;
    const decisions = [];
    for (const m of before.matches) {
      const d = Decision.parse(
        decide(state, envelope(score(m), { id: stableId(m.id), requestId: m.id }))!,
      );
      expect(d.version).toBe(1);
      decisions.push(d);
      state = reduceDecision(state, d);
    }
    expect(state.pools.every((p) => p.order === null && p.orderDecision === undefined)).toBe(true);
    const replayed = decisions.reduce(reduceDecision, captureBaseline(before.baseline!));
    expect(replayed).toEqual(state);
    // A persisted decision is the authority even when replay's present policy differs.
    const future = initial();
    expect(decisions.reduce(reduceDecision, future).pools).toEqual(state.pools);
  });
});
